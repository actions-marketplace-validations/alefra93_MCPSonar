"""``mcpsonar completion SHELL``: print a tab-completion script for bash, zsh, fish or
PowerShell.

The script is generated from the CLI's own argparse parser, so it always lists exactly the
commands, sub-commands, options and option choices of the installed version: there is no
second copy to keep in sync, and no extra dependency. It completes command and option names
and fixed choices (``--format json``); everything else falls back to file names.
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass, field
from typing import Any

from ..output import EXIT_OK

SHELLS = ("bash", "zsh", "fish", "powershell")
BS = chr(92)  # a backslash, spelled out: these scripts are full of shell escapes


@dataclass
class Node:
    """One command level: its options, their choices and its sub-commands."""

    help: str = ""
    options: dict[str, str] = field(default_factory=dict)  # "--format": help
    choices: dict[str, list[str]] = field(default_factory=dict)  # "--format": [...]
    commands: dict[str, Node] = field(default_factory=dict)
    values: list[str] = field(default_factory=list)  # fixed choices of a positional argument


def tree(parser: argparse.ArgumentParser, help_text: str = "") -> Node:
    node = Node(help=help_text)
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            helps = {a.dest: a.help or "" for a in action._choices_actions}
            for name, sub in action.choices.items():
                node.commands[name] = tree(sub, helps.get(name, ""))
            continue
        if action.help == argparse.SUPPRESS:
            continue  # hidden on purpose
        if not action.option_strings and action.choices:
            node.values += [str(c) for c in action.choices]
        for opt in action.option_strings:
            node.options[opt] = action.help if isinstance(action.help, str) else ""
            if action.choices and not isinstance(action.choices, dict):
                node.choices[opt] = [str(c) for c in action.choices]
    return node


def _walk(node: Node, path: tuple[str, ...] = ()):
    yield path, node
    for name, child in node.commands.items():
        yield from _walk(child, (*path, name))


def _one_line(text: str, limit: int = 70) -> str:
    text = " ".join(text.replace("%(default)s", "").split())
    return text if len(text) <= limit else text[: limit - 1] + "…"


# ---- bash (and zsh through bashcompinit) -------------------------------------------- #
def bash(root: Node) -> str:
    transitions = []
    words_opts, words_cmds, choice_cases = [], [], []
    for path, node in _walk(root):
        key = " ".join(path)
        for name in node.commands:
            transitions.append(f'"{key}|{name}"')
        words_opts.append(f'      "{key}") words="{" ".join(node.options)}" ;;')
        if node.commands or node.values:
            words = " ".join([*node.commands, *node.values])
            words_cmds.append(f'      "{key}") words="{words}" ;;')
        for opt, values in node.choices.items():
            choice_cases.append(f'    "{key}|{opt}") words="{" ".join(values)}" ;;')
    return f"""# mcpsonar completion for bash. Generated by `mcpsonar completion bash`.
_mcpsonar() {{
  local cur prev path w i words=""
  cur="${{COMP_WORDS[COMP_CWORD]}}"
  prev="${{COMP_WORDS[COMP_CWORD-1]}}"
  path=""
  for ((i=1; i<COMP_CWORD; i++)); do
    w="${{COMP_WORDS[i]}}"
    case "$w" in -*) continue ;; esac
    case "$path|$w" in
      {"|".join(transitions)}) path="${{path:+$path }}$w" ;;
    esac
  done
  case "$path|$prev" in
{chr(10).join(choice_cases)}
  esac
  if [[ -z "$words" ]]; then
    if [[ "$cur" == -* ]]; then
      case "$path" in
{chr(10).join(words_opts)}
      esac
    else
      case "$path" in
{chr(10).join(words_cmds)}
      esac
    fi
  fi
  [[ -n "$words" ]] && COMPREPLY=($(compgen -W "$words" -- "$cur"))
  return 0
}}
complete -o default -F _mcpsonar mcpsonar
"""


def zsh(root: Node) -> str:
    return ("# mcpsonar completion for zsh. Generated by `mcpsonar completion zsh`.\n"
            "autoload -U +X bashcompinit && bashcompinit\n" + bash(root).split("\n", 1)[1])


# ---- fish ------------------------------------------------------------------------- #
def _fish_quote(text: str) -> str:
    return "'" + text.replace(BS, BS + BS).replace("'", BS + "'") + "'"


def fish(root: Node) -> str:
    lines = ["# mcpsonar completion for fish. Generated by `mcpsonar completion fish`."]
    for path, node in _walk(root):
        if path:
            seen = "; and ".join(f"__fish_seen_subcommand_from {p}" for p in path)
            cond = seen
        else:
            cond = "__fish_use_subcommand"
        if node.commands:
            names = " ".join(node.commands)
            sub_cond = cond if not path else f"{cond}; and not __fish_seen_subcommand_from {names}"
            for name, child in node.commands.items():
                lines.append(f"complete -c mcpsonar -f -n {_fish_quote(sub_cond)} -a {name} "
                             f"-d {_fish_quote(_one_line(child.help))}")
        if node.values:
            lines.append(f"complete -c mcpsonar -f -n {_fish_quote(cond)} "
                         f"-a {_fish_quote(' '.join(node.values))}")
        for opt, help_text in node.options.items():
            flag = f"-l {opt[2:]}" if opt.startswith("--") else f"-s {opt[1:]}"
            extra = ""
            if opt in node.choices:
                extra = f" -x -a {_fish_quote(' '.join(node.choices[opt]))}"
            lines.append(f"complete -c mcpsonar -n {_fish_quote(cond)} {flag}{extra} "
                         f"-d {_fish_quote(_one_line(help_text))}")
    return "\n".join(lines) + "\n"


# ---- PowerShell ------------------------------------------------------------------- #
def _ps_quote(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def powershell(root: Node) -> str:
    cmds, opts, choices, values = [], [], [], []
    for path, node in _walk(root):
        key = _ps_quote(" ".join(path))
        if node.commands:
            cmds.append(f"    {key} = @({', '.join(_ps_quote(c) for c in node.commands)})")
        if node.values:
            values.append(f"    {key} = @({', '.join(_ps_quote(v) for v in node.values)})")
        opts.append(f"    {key} = @({', '.join(_ps_quote(o) for o in node.options)})")
        for opt, allowed in node.choices.items():
            choices.append(f"    {_ps_quote(' '.join(path) + '|' + opt)} = "
                           f"@({', '.join(_ps_quote(v) for v in allowed)})")
    nl = chr(10)
    return f"""# mcpsonar completion for PowerShell. Generated by `mcpsonar completion powershell`.
Register-ArgumentCompleter -Native -CommandName mcpsonar -ScriptBlock {{
  param($wordToComplete, $commandAst, $cursorPosition)
  $commands = @{{
{nl.join(cmds)}
  }}
  $options = @{{
{nl.join(opts)}
  }}
  $choices = @{{
{nl.join(choices)}
  }}
  $values = @{{
{nl.join(values)}
  }}
  $path = ''
  $prev = ''
  foreach ($element in $commandAst.CommandElements | Select-Object -Skip 1) {{
    $text = $element.ToString()
    if ($element.Extent.StartOffset -ge $cursorPosition) {{ break }}
    if ($text -eq $wordToComplete -and $element.Extent.EndOffset -ge $cursorPosition) {{ break }}
    $prev = $text
    if ($text.StartsWith('-')) {{ continue }}
    if ($commands.ContainsKey($path) -and $commands[$path] -contains $text) {{
      $path = ($path + ' ' + $text).Trim()
    }}
  }}
  $words = $choices[$path + '|' + $prev]
  if (-not $words) {{
    if ($wordToComplete.StartsWith('-')) {{ $words = $options[$path] }}
    else {{ $words = @($commands[$path]) + @($values[$path]) | Where-Object {{ $_ }} }}
  }}
  $words | Where-Object {{ $_ -like ($wordToComplete + '*') }} | ForEach-Object {{
    [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_)
  }}
}}
"""


GENERATORS = {"bash": bash, "zsh": zsh, "fish": fish, "powershell": powershell}


def script(shell: str, parser: argparse.ArgumentParser | None = None) -> str:
    if parser is None:
        from ..cli import _build_parser

        parser = _build_parser()
    return GENERATORS[shell](tree(parser))


def register(sub: Any) -> None:
    p = sub.add_parser(
        "completion",
        help="Print a tab-completion script for bash, zsh, fish or PowerShell.",
        description="Print a shell completion script, generated from this version's commands "
        "and options. Install it once, e.g. "
        "`mcpsonar completion bash > ~/.local/share/bash-completion/completions/mcpsonar`. "
        "See docs/cli.md for every shell.",
    )
    p.add_argument("shell", choices=SHELLS)
    p.set_defaults(handler=run)


def run(args: Any) -> int:
    print(script(args.shell), end="")
    return EXIT_OK
